#!/usr/bin/env python3
"""The fonts of the menu (docs/PLAN.md Ф2): Noto Sans Regular (SIL Open Font License 1.1, Google;
the system font of fonts-noto-core) rendered with anti-aliasing to 4 bits a pixel (16 levels of
coverage): f27 (ASCII 32..126 and Cyrillic U+0400..U+045F, U+0490 / U+0491) for all the text, in
the size of the ROM font 27 of the FT812 menu; f30 (32..64: digits and signs) for the clock; f20
(ASCII) for the small labels of the Gamepad page.

  mkfonts.py OUT.h [TTF]

Output: one C header with, per font, the code ranges (first code point, count, first glyph), the
glyph table (8 bytes a glyph, every code point of a range: bitmap offset, width, height, x offset,
y offset from the top of the line, advance, 1 if the font has no such glyph) and the bitmaps, two
pixels a byte (the left one in the low nibble), each row padded to a whole byte."""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf"
ASCII = [(32, 126)]
CYRILLIC = ASCII + [(0x400, 0x45F), (0x490, 0x491)]
# name, pixel size, code ranges: f20 the small labels of the Gamepad page, f27 all the text (font 27 of
# the FT812 menu: buttons, core names, Setup), f30 the clock (digits and signs only, 32..64)
FONTS = [("f20", 9, ASCII), ("f27", 16, CYRILLIC), ("f30", 30, [(32, 64)])]

out = ["// generated by tools/mkfonts.py from Noto Sans Regular (SIL Open Font License 1.1,",
       "// https://openfontlicense.org; Copyright 2022 The Noto Project Authors): do not edit",
       "#pragma once", "#include \"font.h\"", ""]
for name, px, ranges in FONTS:
    font = ImageFont.truetype(TTF, px)
    ascent, descent = font.getmetrics()
    glyphs, data, rtab = [], bytearray(), []
    for first, last in ranges:
        rtab.append((first, last - first + 1, len(glyphs)))
        for cp in range(first, last + 1):
            ch = chr(cp)
            if font.getmask(ch).size == (0, 0) and ch != " ":
                glyphs.append((0, 0, 0, 0, 0, 0, 1))  # not in the font: '?' is drawn
                continue
            adv = round(font.getlength(ch))
            l, t, r, b = font.getbbox(ch)  # relative to the top of the line (the ascent)
            w, h = max(0, r - l), max(0, b - t)
            off = len(data)
            if w and h:
                img = Image.new("L", (w, h), 0)
                ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
                for y in range(h):
                    row = [img.getpixel((x, y)) * 15 // 255 for x in range(w)]
                    if len(row) % 2:
                        row.append(0)
                    for x in range(0, len(row), 2):
                        data.append(row[x] | (row[x + 1] << 4))
            assert off < 65536 and w < 256 and h < 256 and -128 <= l < 128 and -128 <= t < 128 and adv < 256
            glyphs.append((off, w, h, l, t, adv, 0))
    out.append(f"static const uint8_t {name}_bits[{max(1, len(data))}] = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    if not data:
        out.append("  0")
    out.append("};")
    out.append(f"static const font_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
    for g in glyphs:
        out.append("  {{ {}, {}, {}, {}, {}, {}, {} }},".format(*g))
    out.append("};")
    out.append(f"static const font_range_t {name}_ranges[{len(rtab)}] = {{")
    for r in rtab:
        out.append("  {{ 0x{:04x}, {}, {} }},".format(*r))
    out.append("};")
    out.append(f"const font_t {name} = {{ {name}_glyphs, {name}_bits, {name}_ranges, {len(rtab)}, {ascent + descent}, {ascent} }};")
    out.append("")
    print(f"{name}: {px} px, {len(glyphs)} glyphs, {len(data)} bytes, line {ascent + descent}", file=sys.stderr)
open(sys.argv[1], "w").write("\n".join(out))
