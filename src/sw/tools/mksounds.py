#!/usr/bin/env python3
"""The sounds of the menu (docs/PLAN.md Ф2) from the firmware (karabas-go-firmware src/ui/bitmaps.h:
the start sounds key1..key4 of the FT812 menu, u-law for its audio engine) as raw signed 16-bit
little-endian mono PCM for the player of the menu.

  mksounds.py BITMAPS_H OUT.bin OUT.h [BASE]

OUT.bin is the ROM of boot.kg (core.json roms, at BASE in the SRAM, default 0x200000); OUT.h has
the table: per sound its address in the SRAM, its length in samples and its rate."""
import re, struct, sys

src = open(sys.argv[1]).read()
base = int(sys.argv[4], 0) if len(sys.argv) > 4 else 0x200000

def define(name):
    v = re.search(r"#define " + name + r"\s+(\w+)", src).group(1)
    return int(v) if v.isdigit() else define(v)   # a define of another define

def array(name):
    m = re.search(name + r"\[\]\s*=\s*\{(.*?)\};", src, re.S)
    return bytes(int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(1)))

def ulaw(b):  # G.711 u-law to 16 bit
    b = ~b & 0xFF
    sign, exp, mant = b & 0x80, (b >> 4) & 7, b & 0x0F
    v = ((mant << 3) + 0x84) << exp
    v -= 0x84
    return -v if sign else v

blob = bytearray()
table = []
for k in range(1, 5):
    data = array(f"key{k}Data")
    start, size, rate = define(f"KEY{k}_PCM_START"), define(f"KEY{k}_PCM_SIZE"), define(f"KEY{k}_SAMPLERATE")
    pcm = [ulaw(b) for b in data[start:start + size]]
    while len(blob) % 4:
        blob.append(0)
    table.append((base + len(blob), len(pcm), rate))
    blob += b"".join(struct.pack("<h", v) for v in pcm)
open(sys.argv[2], "wb").write(blob)
out = ["// generated by tools/mksounds.py from karabas-go-firmware src/ui/bitmaps.h: do not edit",
       "#pragma once", "#include <stdint.h>", "",
       "typedef struct { uint32_t addr, samples, rate; } sound_t;  // raw s16le mono in the SRAM",
       f"#define SOUNDS_BASE 0x{base:06x}", f"#define SOUNDS_END 0x{base + len(blob):06x}",
       f"static const sound_t sounds[{len(table)}] = {{  // the start sounds 1..4 of [ft812] sound"]
out += [f"  {{ 0x{a:06x}, {n}, {r} }}," for a, n, r in table]
out.append("};")
open(sys.argv[3], "w").write("\n".join(out) + "\n")
print(f"sounds: {len(table)}, {len(blob)} bytes at 0x{base:06x}", file=sys.stderr)
