#!/usr/bin/env python3
"""The pictures of the FT812 menu for the self-drawing menu (docs/PLAN.md Ф2), taken from the
firmware (karabas-go-firmware src/ui/bitmaps.h: PNG files for CMD_LOADIMAGE, the FT812 decodes them
to RGB565): the logo of the
board (56 x 16, drawn x4) and the character (BG_ID 2, 160 x 200).

  mkimages.py BITMAPS_H OUT.h [--png DIR]

The logo goes out as colour indexes into a small palette (LOGO_PAL, black = transparent); the
character as 4-bit coverage of white (its pixels are grey levels over black)."""
import io, re, sys
from PIL import Image

src = open(sys.argv[1]).read()
outp = sys.argv[2]
png_dir = sys.argv[sys.argv.index("--png") + 1] if "--png" in sys.argv else None

def block(cond):
    # the text between "#if/#elif <cond>" and the next #elif / #else / #endif
    m = re.search(r"#(?:el)?if " + re.escape(cond) + r"\n(.*?)\n#(?:elif|else|endif)", src, re.S)
    return m.group(1)

def array(text, name):
    m = re.search(name + r"\[\]\s*=\s*\{(.*?)\};", text, re.S)
    return bytes(int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(1)))

def png(data, w, h):
    im = Image.open(io.BytesIO(data)).convert("RGB")
    assert im.size == (w, h), im.size
    return list(im.getdata())

logo = png(array(block("HW_ID==HW_ID_MINI || HW_ID==HW_ID_MINIG"), "logoData"), 56, 16)
char = png(array(block("BG_ID==2"), "bgData"), 160, 200)

if png_dir:
    for name, px, w, h in (("logo", logo, 56, 16), ("char", char, 160, 200)):
        im = Image.new("RGB", (w, h)); im.putdata(px); im.save(f"{png_dir}/{name}.png")

pal = [(0, 0, 0)]
idx = []
for p in logo:
    if p not in pal:
        pal.append(p)
    idx.append(pal.index(p))
assert len(pal) <= 16, len(pal)
cov = [max(p) * 15 // 255 for p in char]

out = ["// generated by tools/mkimages.py from karabas-go-firmware src/ui/bitmaps.h: do not edit",
       "#pragma once", "#include <stdint.h>", "",
       "#define LOGO_W 56", "#define LOGO_H 16", f"#define LOGO_COLORS {len(pal)}",
       "static const uint32_t logo_pal[LOGO_COLORS] = { " + ", ".join(f"0x{r:02x}{g:02x}{b:02x}" for r, g, b in pal) + " };",
       "static const uint8_t logo_px[LOGO_W * LOGO_H] = {"]
for i in range(0, len(idx), 56):
    out.append("  " + ",".join(str(v) for v in idx[i:i + 56]) + ",")
out += ["};", "", "#define CHAR_W 160", "#define CHAR_H 200",
        "static const uint8_t char_cov[CHAR_W * CHAR_H / 2] = {  // two pixels a byte, the left one low"]
packed = [cov[i] | (cov[i + 1] << 4) for i in range(0, len(cov), 2)]
for i in range(0, len(packed), 40):
    out.append("  " + ",".join(f"0x{v:02x}" for v in packed[i:i + 40]) + ",")
out.append("};")
open(outp, "w").write("\n".join(out) + "\n")
print(f"logo {len(pal)} colours, char {sum(1 for c in cov if c)} pixels", file=sys.stderr)
